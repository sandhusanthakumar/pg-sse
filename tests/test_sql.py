@pytest.mark.parametrize("schema_qualified", [False, True])
def test_dropping_leaves_no_triggers_or_functions(db, schema_qualified):
    execute(db.dsn, "CREATE TABLE messages (id bigserial PRIMARY KEY, room text NOT NULL)")
    table = f"{db.schema}.messages" if schema_qualified else "messages"
    execute(db.dsn, trigger_sql(table, "room", db.channel, order_column="id"))
    triggers = "SELECT count(*) FROM pg_trigger WHERE tgrelid = 'messages'::regclass AND NOT tgisinternal"
    functions = "SELECT count(*) FROM pg_proc WHERE proname LIKE 'pg_sse$%%' AND pronamespace = %s::regnamespace"
    assert execute(db.dsn, triggers) == [(2,)]
    assert execute(db.dsn, functions, (db.schema,)) == [(2,)]
    execute(db.dsn, drop_trigger_sql(table, "room", order_column="id"))
    assert execute(db.dsn, triggers) == [(0,)]
    assert execute(db.dsn, functions, (db.schema,)) == [(0,)]
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO messages (room) VALUES ('a')")
        assert _payloads(listener) == []


def test_two_tables_whose_names_overlap_get_different_triggers(db):
    execute(db.dsn, "CREATE TABLE a_b (id bigserial PRIMARY KEY, c text NOT NULL)")
    execute(db.dsn, "CREATE TABLE a (id bigserial PRIMARY KEY, b_c text NOT NULL)")
    execute(db.dsn, trigger_sql("a_b", "c", db.channel))
    execute(db.dsn, trigger_sql("a", "b_c", db.channel))
    names = execute(
        db.dsn,
        "SELECT proname FROM pg_proc WHERE proname LIKE 'pg_sse$notify$%%' AND pronamespace = %s::regnamespace",
        (db.schema,),
    )
    assert sorted(name for (name,) in names) == ["pg_sse$notify$a$b_c", "pg_sse$notify$a_b$c"]
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO a_b (c) VALUES ('x')")
        execute(db.dsn, "INSERT INTO a (b_c) VALUES ('y')")
        assert _payloads(listener) == ["x", "y"]


