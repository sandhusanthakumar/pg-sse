import threading
import time

import psycopg
import pytest
from helpers import execute, make_table

from pg_sse import drop_trigger_sql, trigger_sql


@pytest.mark.parametrize(
    ("table", "key", "channel", "order"),
    [
        ("Messages", "room", "c", None),
        ("messages", "room-id", "c", None),
        ("messages", "room", "c;drop", None),
        ("messages", "room", "c", "Id"),
        ("bad schema.messages", "room", "c", None),
        ("", "room", "c", None),
    ],
)
def test_only_plain_lower_case_identifiers(table, key, channel, order):
    with pytest.raises(ValueError, match="identifier"):
        trigger_sql(table, key, channel, order_column=order)


def test_a_generated_name_over_63_bytes_is_refused():
    with pytest.raises(ValueError, match="63 bytes"):
        trigger_sql("t" * 40, "k" * 30, "c")


def _listen(dsn: str, channel: str) -> psycopg.Connection:
    conn = psycopg.connect(dsn, autocommit=True)
    conn.execute(f'LISTEN "{channel}"')
    return conn


def _payloads(conn: psycopg.Connection) -> list[str]:
    return [n.payload for n in conn.notifies(timeout=0.3)]


def test_every_write_notifies_its_key(db):
    make_table(db)
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO messages (room, body) VALUES ('a', 'x')")
        assert _payloads(listener) == ["a"]
        execute(db.dsn, "UPDATE messages SET body = 'y'")
        assert _payloads(listener) == ["a"]
        execute(db.dsn, "UPDATE messages SET room = 'b'")
        assert _payloads(listener) == ["a", "b"]
        execute(db.dsn, "DELETE FROM messages")
        assert _payloads(listener) == ["b"]


def test_a_rolled_back_write_announces_nothing(db):
    make_table(db)
    with _listen(db.dsn, db.channel) as listener:
        with psycopg.connect(db.dsn) as conn:
            conn.execute("INSERT INTO messages (room) VALUES ('a')")
            conn.rollback()
        assert _payloads(listener) == []


def test_running_it_twice_is_harmless(db):
    make_table(db, order_column="id")
    execute(db.dsn, trigger_sql("messages", "room", db.channel, order_column="id"))  # again
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO messages (room) VALUES ('a')")
        assert _payloads(listener) == ["a"]


def test_a_schema_qualified_table(db):
    execute(db.dsn, "CREATE TABLE messages (id bigserial PRIMARY KEY, room text NOT NULL)")
    execute(db.dsn, trigger_sql(f"{db.schema}.messages", "room", db.channel, order_column="id"))
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO messages (room) VALUES ('a')")
        assert _payloads(listener) == ["a"]


@pytest.mark.parametrize(
    "id_column",
    [
        "id bigserial PRIMARY KEY",
        "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY",
    ],
)
def test_ids_follow_commit_order_within_a_key(db, id_column):
    execute(db.dsn, f"CREATE TABLE messages ({id_column}, room text NOT NULL)")
    execute(db.dsn, trigger_sql("messages", "room", db.channel, order_column="id"))

    first = psycopg.connect(db.dsn)
    first_id = first.execute("INSERT INTO messages (room) VALUES ('a') RETURNING id").fetchone()[0]

    # The same room waits for the first writer to commit, then draws a later id.
    second: dict = {}

    def insert_same_room():
        second["id"] = execute(db.dsn, "INSERT INTO messages (room) VALUES ('a') RETURNING id")[0][0]

    writer = threading.Thread(target=insert_same_room)
    writer.start()
    time.sleep(0.3)
    assert writer.is_alive(), "the second writer to room a should wait for the first"
    # Another room is not held up.
    other_id = execute(db.dsn, "INSERT INTO messages (room) VALUES ('b') RETURNING id")[0][0]
    first.commit()
    first.close()
    writer.join(timeout=5)

    assert second["id"] > first_id
    assert second["id"] > other_id  # drawn after the wait, not when the statement began


def test_an_order_column_without_a_sequence_is_refused_at_install(db):
    execute(db.dsn, "CREATE TABLE messages (id bigint PRIMARY KEY, room text NOT NULL)")
    with pytest.raises(psycopg.errors.RaiseException, match="no sequence"):
        execute(db.dsn, trigger_sql("messages", "room", db.channel, order_column="id"))
    triggers = "SELECT count(*) FROM pg_trigger WHERE tgrelid = 'messages'::regclass AND NOT tgisinternal"
    assert execute(db.dsn, triggers) == [(0,)]  # the guard runs first: nothing was installed


def test_the_order_trigger_replaces_a_supplied_id(db):
    make_table(db, order_column="id")
    assert execute(db.dsn, "INSERT INTO messages (id, room) VALUES (1000, 'a') RETURNING id")[0][0] != 1000


@pytest.mark.parametrize("schema_qualified", [False, True])
def test_dropping_leaves_no_triggers_or_functions(db, schema_qualified):
    execute(db.dsn, "CREATE TABLE messages (id bigserial PRIMARY KEY, room text NOT NULL)")
    table = f"{db.schema}.messages" if schema_qualified else "messages"
    execute(db.dsn, trigger_sql(table, "room", db.channel, order_column="id"))
    triggers = "SELECT count(*) FROM pg_trigger WHERE tgrelid = 'messages'::regclass AND NOT tgisinternal"
    functions = "SELECT count(*) FROM pg_proc WHERE proname LIKE 'pg_sse$%%' AND pronamespace = %s::regnamespace"
    assert execute(db.dsn, triggers) == [(2,)]
    assert execute(db.dsn, functions, (db.schema,)) == [(2,)]
    execute(db.dsn, drop_trigger_sql(table, "room", order_column="id"))
    assert execute(db.dsn, triggers) == [(0,)]
    assert execute(db.dsn, functions, (db.schema,)) == [(0,)]
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO messages (room) VALUES ('a')")
        assert _payloads(listener) == []


def test_two_tables_whose_names_overlap_get_different_triggers(db):
    execute(db.dsn, "CREATE TABLE a_b (id bigserial PRIMARY KEY, c text NOT NULL)")
    execute(db.dsn, "CREATE TABLE a (id bigserial PRIMARY KEY, b_c text NOT NULL)")
    execute(db.dsn, trigger_sql("a_b", "c", db.channel))
    execute(db.dsn, trigger_sql("a", "b_c", db.channel))
    names = execute(
        db.dsn,
        "SELECT proname FROM pg_proc WHERE proname LIKE 'pg_sse$notify$%%' AND pronamespace = %s::regnamespace",
        (db.schema,),
    )
    assert sorted(name for (name,) in names) == ["pg_sse$notify$a$b_c", "pg_sse$notify$a_b$c"]
    with _listen(db.dsn, db.channel) as listener:
        execute(db.dsn, "INSERT INTO a_b (c) VALUES ('x')")
        execute(db.dsn, "INSERT INTO a (b_c) VALUES ('y')")
        assert _payloads(listener) == ["x", "y"]


